-- ExamGuard 초기 스키마 (노션 ERD 2026-11-18 기준)
-- 시간 컬럼은 모두 TIMESTAMPTZ, enum 성격 컬럼은 VARCHAR + CHECK

CREATE TABLE users
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id   VARCHAR(50)  NOT NULL UNIQUE,
    password   VARCHAR(255) NOT NULL,
    name       VARCHAR(50)  NOT NULL,
    role       VARCHAR(20)  NOT NULL CHECK (role IN ('STUDENT', 'ADMIN')),
    created_at TIMESTAMPTZ  NOT NULL
);

-- 상태(DRAFT/PUBLISHED/OPEN/CLOSED)는 저장하지 않고 published_at, start_at, end_at으로 계산
CREATE TABLE exams
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(200) NOT NULL,
    code         VARCHAR(6) UNIQUE,                -- publish 때 발급, DRAFT는 NULL
    start_at     TIMESTAMPTZ,                      -- DRAFT에서는 NULL 가능
    end_at       TIMESTAMPTZ,                      -- 조기 종료 시 현재 시각으로 변경
    published_at TIMESTAMPTZ,                      -- NULL이면 DRAFT
    created_by   BIGINT       NOT NULL REFERENCES users (id),
    created_at   TIMESTAMPTZ  NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL
);

CREATE TABLE questions
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT      NOT NULL REFERENCES exams (id),
    seq     INT         NOT NULL,
    type    VARCHAR(20) NOT NULL CHECK (type IN ('MULTIPLE_CHOICE', 'SHORT_ANSWER')),
    content TEXT        NOT NULL,
    options JSONB,                                 -- 객관식 보기 4개(문자열 배열), 단답형은 NULL
    answer  VARCHAR(255),                          -- 객관식은 보기 인덱스 0~3, 단답형은 문자열. DRAFT에서는 NULL 가능
    CONSTRAINT uq_questions_exam_seq UNIQUE (exam_id, seq)
);

CREATE TABLE attempts
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id         BIGINT      NOT NULL REFERENCES exams (id),
    user_id         BIGINT      NOT NULL REFERENCES users (id),
    status          VARCHAR(20) NOT NULL CHECK (status IN ('WAITING', 'IN_PROGRESS', 'SUBMITTED')),
    answers         JSONB       NOT NULL DEFAULT '{}', -- { "문항id": 보기 인덱스 또는 문자열 }
    version         INT         NOT NULL DEFAULT 0,    -- 저장된 version보다 큰 요청만 반영
    answered_count  INT         NOT NULL DEFAULT 0,
    save_fail_count INT         NOT NULL DEFAULT 0,
    joined_at       TIMESTAMPTZ NOT NULL,
    started_at      TIMESTAMPTZ,
    last_saved_at   TIMESTAMPTZ,
    submitted_at    TIMESTAMPTZ,
    CONSTRAINT uq_attempts_exam_user UNIQUE (exam_id, user_id) -- 한 시험에 학생당 응시 1건
);
